/// The receivers of the generated methods, which no local or parameter takes
const READER: &str = "t";
const FIELDS: &str = "f";
const STRUCT: &str = "s";
const VIEW: &str = "v";

/// The error that a getter returns, in documentation
const DECODE_ERROR: &str = "[*tafla.DecodeError]";

pub fn generate(
    schema: &Schema,
    stem: &str,
    file_name: &str,
    options: &Options,
) -> Vec<GeneratedFile> {
    let runtime = options.runtime.as_deref().unwrap_or(RUNTIME);
    let generator = Generator::new(schema);

    let mut writer = CodeWriter::new("\t");
    // The form that tools such as linters recognize as generated code
    writer.line(format!(
        "// Code generated by tafla-gen from {file_name}. DO NOT EDIT."
    ));
    writer.blank();
    writer.line(format!("package {}", package_name(stem)));
    generator.imports(&mut writer, runtime);

    for (index, definition) in schema.definitions.iter().enumerate() {
        match definition.kind {
            Kind::Message(layout) => generator.message(&mut writer, definition, layout),
            Kind::Table => generator.table(&mut writer, definition),
            Kind::Struct(_) => generator.structure(&mut writer, definition),
        }
        if !definition.is_struct() {
            generator.fields_struct(&mut writer, index);
        }

        if schema.is_item(index) {
            if definition.is_struct() {
                struct_array_view(&mut writer, definition);
            } else {
                vector_view(&mut writer, definition);
            }
        }
    }

    vec![GeneratedFile {
        path: format!("{stem}.go"),
        contents: writer.finish(),
    }]
}

/// The package of the code generated from the schema `stem`: its ASCII
/// letters and digits, in lowercase, as Go names packages. A keyword takes a
/// `_` after it, and a name that would be empty or start with a digit is
/// prefixed with `schema`.
fn package_name(stem: &str) -> String {
    let name: String = stem
        .chars()
        .filter(char::is_ascii_alphanumeric)
        .map(|character| character.to_ascii_lowercase())
        .collect();

    if name.is_empty() || name.starts_with(|character: char| character.is_ascii_digit()) {
        format!("schema{name}")
    } else if KEYWORDS.contains(&name.as_str()) {
        format!("{name}_")
    } else {
        name
    }
}

struct Generator<'a> {
    schema: &'a Schema,
    /// The byte length of each table whose fields' sizes the schema fixes,
    /// which the generated code writes whole, by its index, and `None` for
    /// every other definition
    fixed_tables: Vec<Option<usize>>,
}

/// The offset size of nested tables, which have `uint32` offsets, since the
/// checker rejects tables nested in messages of a narrower offset type
const NESTED_OFFSET_SIZE: usize = 4;

/// The longest that the generated code lays out a table's fields, so that
/// their positions are constants that an `int` holds on 32-bit hosts too.
/// Longer ones, which no table that fits in memory there holds, it writes
/// with the runtime's sizer and writer.
const MAX_LAID_OUT: usize = i32::MAX as usize;

/// The fields of a message or table that the generated code lays out itself,
/// rather than the runtime's sizer and writer: its first fields of fixed size,
/// when there are at least two, which they take together, or a message's
/// fields when they're all of fixed size but a string after them
struct Plan {
    /// The byte length of a message's header slots, before its offsets
    header: usize,
    /// The offset size of the table's header slots, offsets and counts
    width: usize,
    /// How many of the first fields the generated code lays out
    fixed: usize,
    /// The byte length of those fields, after the offsets
    bytes: usize,
    /// Whether they're the whole message's but a string after them, which
    /// the generated code writes without a sizer and a writer
    whole: bool,
}

impl Plan {
    /// Where the fields that the generated code lays out end, from the
    /// table's start: after its header, its offsets and those fields
    const fn end(&self, fields: usize) -> usize {
        self.header + fields * self.width + self.bytes
    }
}

impl<'a> Generator<'a> {
    fn new(schema: &'a Schema) -> Self {
        let mut fixed_tables = vec![None; schema.definitions.len()];
        let mut visited = vec![false; schema.definitions.len()];
        for index in 0..schema.definitions.len() {
            fixed_table_size(schema, index, &mut fixed_tables, &mut visited);
        }

        Generator {
            schema,
            fixed_tables,
        }
    }

    /// The byte length of a field whose size the schema fixes: a scalar, a
    /// struct, or a table of only such fields, which has no padding
    fn fixed_size(&self, field_type: FieldType) -> Option<usize> {
        fixed_field_size(self.schema, field_type, |index| self.fixed_tables[index])
    }

    /// The fields of a message or table that the generated code lays out
    /// itself, which fit in its offset type
    fn plan(&self, definition: &Definition) -> Plan {
        let (header, width, max_length) = match definition.kind {
            Kind::Message(layout) => {
                let width = offset_size(layout.offset_type);
                let slots = usize::from(layout.sized) + usize::from(layout.version.is_some());
                (slots * width, width, layout.offset_type.max_value())
            }
            Kind::Table | Kind::Struct(_) => {
                (0, NESTED_OFFSET_SIZE, OffsetType::Uint32.max_value())
            }
        };
        let max_length =
            usize::try_from(max_length).map_or(MAX_LAID_OUT, |max| max.min(MAX_LAID_OUT));

        let mut fixed = 0;
        let mut bytes = 0_usize;
        for field in &definition.fields {
            let Some(size) = self.fixed_size(field.field_type) else {
                break;
            };
            fixed += 1;
            bytes = bytes.saturating_add(size);
        }

        let fits = header
            .saturating_add(definition.fields.len().saturating_mul(width))
            .saturating_add(bytes)
            <= max_length;
        let rest = &definition.fields[fixed..];
        let whole = matches!(definition.kind, Kind::Message(_))
            && fits
            && (rest.is_empty() || (rest.len() == 1 && rest[0].field_type == FieldType::String));

        // Fewer than two fields together save no call
        let laid_out = whole || (fits && fixed >= 2);
        Plan {
            header,
            width,
            fixed: if laid_out { fixed } else { 0 },
            bytes: if laid_out { bytes } else { 0 },
            whole,
        }
    }

    fn imports(&self, writer: &mut CodeWriter, runtime: &str) {
        let definitions = &self.schema.definitions;
        // A schema without definitions imports nothing
        if definitions.is_empty() {
            return;
        }

        let struct_scalars: Vec<Scalar> = definitions
            .iter()
            .filter(|definition| definition.is_struct())
            .flat_map(|definition| &definition.fields)
            .filter_map(|field| match field.field_type {
                FieldType::Scalar(scalar) => Some(scalar),
                _ => None,
            })
            .collect();

        // The scalars and offsets that the generated code writes itself
        let (laid_out_scalars, wide_offsets) = self.laid_out();
        let scalars = || struct_scalars.iter().chain(&laid_out_scalars);

        let mut standard = Vec::new();
        if wide_offsets || scalars().any(|scalar| scalar.size() > 1) {
            standard.push("encoding/binary");
        }
        if (0..definitions.len()).any(|index| self.schema.is_item(index)) {
            standard.push("iter");
        }
        if scalars().any(|scalar| matches!(scalar, Scalar::Float32 | Scalar::Float64)) {
            standard.push("math");
        }

        writer.blank();
        writer.open("import (");
        for package in &standard {
            writer.line(format!("\"{package}\""));
        }
        if !standard.is_empty() {
            writer.blank();
        }
        writer.line(format!("tafla \"{}\"", go_string(runtime)));
        writer.close(")");
    }

    /// The scalars of the fields that the generated code lays out itself, and
    /// whether it writes offsets wider than a byte
    fn laid_out(&self) -> (Vec<Scalar>, bool) {
        let mut scalars = Vec::new();
        let mut wide_offsets = false;
        for (index, definition) in self.schema.definitions.iter().enumerate() {
            if definition.is_struct() {
                continue;
            }

            let (fields, width) = if self.fixed_tables[index].is_some() {
                (definition.fields.as_slice(), NESTED_OFFSET_SIZE)
            } else {
                let plan = self.plan(definition);
                // A string after a message's fields has its offset and count
                let count = if plan.whole {
                    definition.fields.len()
                } else {
                    plan.fixed
                };
                (&definition.fields[..count], plan.width)
            };

            wide_offsets |= !fields.is_empty() && width > 1;
            scalars.extend(fields.iter().filter_map(|field| match field.field_type {
                FieldType::Scalar(scalar) => Some(scalar),
                _ => None,
            }));
        }

        (scalars, wide_offsets)
    }

    fn message(&self, writer: &mut CodeWriter, definition: &Definition, layout: Layout) {
        let name = &definition.name;

        writer.blank();
        writer.lines(&go_doc(&definition.docs));
        writer.open(format!("type {name} struct {{"));
        writer.line("bytes []byte");
        writer.close("}");

        if let Some(version) = layout.version {
            writer.blank();
            writer.lines(&prose(&[
                format!("{name}FormatVersion is the version of the format, which the header"),
                format!("carries and [New{name}] checks."),
            ]));
            writer.line(format!("const {name}FormatVersion uint32 = {version}"));

            writer.blank();
            writer.lines(&prose(&[
                format!(
                    "New{name} reads {} from bytes, which it keeps rather",
                    article(name)
                ),
                format!("than copying them. It fails with a {DECODE_ERROR} if bytes are"),
                "in another format version.".to_owned(),
            ]));
            writer.open(format!("func New{name}(bytes []byte) ({name}, error) {{"));
            writer.line(format!("version, err := {name}VersionOf(bytes)"));
            writer.open("if err != nil {");
            writer.line(format!("return {name}{{}}, err"));
            writer.close("}");
            writer.open(format!("if version != {name}FormatVersion {{"));
            writer.line(format!(
                "return {name}{{}}, tafla.NewUnsupportedVersionError(version, {name}FormatVersion)"
            ));
            writer.close("}");
            writer.blank();
            writer.line(format!("return {name}{{bytes: bytes}}, nil"));
            writer.close("}");

            writer.blank();
            writer.lines(&prose(&[
                format!("{name}VersionOf returns the format version in the header of bytes,"),
                "without checking it, so that an application can choose the reader of".to_owned(),
                format!("that version. It fails with a {DECODE_ERROR} if the header"),
                "doesn't fit in bytes.".to_owned(),
            ]));
            writer.open(format!(
                "func {name}VersionOf(bytes []byte) (uint32, error) {{"
            ));
            writer.line(format!(
                "return tafla.NewByteBuffer(bytes, {name}{{}}.layout()).Version()"
            ));
            writer.close("}");
        } else {
            writer.blank();
            writer.lines(&prose(&[
                format!(
                    "New{name} reads {} from bytes, which it keeps rather",
                    article(name)
                ),
                "than copying them.".to_owned(),
            ]));
            writer.open(format!("func New{name}(bytes []byte) {name} {{"));
            writer.line(format!("return {name}{{bytes: bytes}}"));
            writer.close("}");
        }

        writer.blank();
        writer.lines(&prose(&[format!(
            "layout returns the layout of {}, which its getters read it in",
            article(name)
        )]));
        writer.open(format!("func ({name}) layout() tafla.TableLayout {{"));
        writer.line(format!("return {}", layout_expression(layout)));
        writer.close("}");

        self.getters(writer, definition, true);
    }

    fn table(&self, writer: &mut CodeWriter, definition: &Definition) {
        let name = &definition.name;

        writer.blank();
        writer.lines(&go_doc(&definition.docs));
        writer.open(format!("type {name} struct {{"));
        writer.line("bytes    []byte");
        writer.line("position int");
        writer.close("}");

        self.getters(writer, definition, false);
    }

    fn getters(&self, writer: &mut CodeWriter, definition: &Definition, is_root: bool) {
        let name = &definition.name;
        // Each getter reads with a buffer in the table's layout, a constant,
        // rather than one that the reader holds, so that its reads compile
        // for that layout's offset type where they're inlined
        let buffer = if is_root {
            format!("buffer := tafla.NewByteBuffer({READER}.bytes, {READER}.layout())")
        } else {
            format!("buffer := tafla.NewByteBuffer({READER}.bytes, tafla.TableLayout{{}})")
        };

        for (index, field) in definition.fields.iter().enumerate() {
            let offset = if is_root {
                format!("buffer.RootOffset({index})")
            } else {
                format!("buffer.FieldOffset({READER}.position, {index})")
            };
            let getter = exported(&field.name);
            let value_type = self.value_type(field.field_type);

            writer.blank();
            writer.lines(&go_doc(&getter_docs(
                &getter,
                &field.docs,
                "if the field lies outside the bytes.",
            )));
            writer.open(format!(
                "func ({READER} {name}) {getter}() ({value_type}, error) {{"
            ));
            writer.line(&buffer);
            find_field(writer, &offset, &zero_value(&value_type));

            match field.field_type {
                FieldType::Scalar(Scalar::Bool) => {
                    writer.line("value, err := buffer.GetUint8(position)");
                    writer.line("return value != 0, err");
                }
                FieldType::Scalar(scalar) => {
                    writer.line(format!("return buffer.Get{}(position)", method(scalar)));
                }
                FieldType::Array(scalar) => {
                    writer.line(format!(
                        "return buffer.Get{}Array(position)",
                        method(scalar)
                    ));
                }
                FieldType::String => writer.line("return buffer.GetString(position)"),
                FieldType::Struct(index) => {
                    let structure = self.schema.definition(index);
                    let size = structure.struct_layout().size;
                    writer.line(format!("bytes, err := buffer.GetStruct(position, {size})"));
                    return_on_error(writer, &format!("{}{{}}", structure.name));
                    writer.line(format!("var value {}", structure.name));
                    writer.line("value.read(bytes)");
                    writer.line("return value, nil");
                }
                FieldType::StructArray(index) => {
                    let structure = self.schema.definition(index);
                    let size = structure.struct_layout().size;
                    writer.line(format!(
                        "bytes, err := buffer.GetStructArray(position, {size})"
                    ));
                    return_on_error(writer, "nil");
                    writer.line(format!(
                        "items := make([]{}, len(bytes)/{size})",
                        structure.name
                    ));
                    writer.open("for index := range items {");
                    writer.line(format!("items[index].read(bytes[index*{size}:])"));
                    writer.close("}");
                    writer.line("return items, nil");
                }
                FieldType::Table(index) => {
                    let table = &self.schema.definition(index).name;
                    writer.line(format!(
                        "return {table}{{bytes: {READER}.bytes, position: position}}, nil"
                    ));
                }
                FieldType::Vector(index) => {
                    let table = &self.schema.definition(index).name;
                    writer.line("vector, err := buffer.GetVector(position)");
                    return_on_error(writer, "nil");
                    writer.line(format!("items := make([]{table}, 0, vector.Len())"));
                    // Each item is read in place, from its bytes and those
                    // after it in the message
                    writer.open("for bytes, err := range vector.ItemsInPlace() {");
                    writer.open("if err != nil {");
                    writer.line("return nil, err");
                    writer.close("}");
                    writer.line(format!("items = append(items, {table}{{bytes: bytes}})"));
                    writer.close("}");
                    writer.line("return items, nil");
                }
            }
            writer.close("}");

            if matches!(
                field.field_type,
                FieldType::Vector(_) | FieldType::StructArray(_)
            ) {
                self.view_getter(writer, definition, field, &buffer, &offset);
            }
        }
    }

    /// The getter of a view of a vector or an array of structs, which reads
    /// each item when it's asked for, rather than all of them as the
    /// field's own getter does. It finds the field as the field's getter
    /// does, with `buffer`'s line and the `offset` it reads.
    fn view_getter(
        &self,
        writer: &mut CodeWriter,
        definition: &Definition,
        field: &Field,
        buffer: &str,
        offset: &str,
    ) {
        let (view, errors) = match field.field_type {
            FieldType::Vector(index) => (
                format!("{}Vector", self.schema.definition(index).name),
                "if the field, or the vector's count or the ends of its items, lie outside the bytes.",
            ),
            FieldType::StructArray(index) => (
                format!("{}Array", self.schema.definition(index).name),
                "if the field or its structs lie outside the bytes.",
            ),
            _ => unreachable!("only vectors and arrays of structs have views"),
        };
        let getter = exported(&field.name);
        let view_getter = format!("{}View", pascal_case(&field.name));

        let mut docs = field.docs.clone();
        if !docs.is_empty() {
            docs.push(String::new());
        }
        let lead = if docs.is_empty() {
            format!("{view_getter} views")
        } else {
            "It views".to_owned()
        };
        docs.extend(wrap(&format!(
            "{lead} the items of [{}.{getter}], reading each one when it's asked for. \
             It fails with a {DECODE_ERROR} {errors}",
            definition.name
        )));

        writer.blank();
        writer.lines(&go_doc(&docs));
        writer.open(format!(
            "func ({READER} {}) {view_getter}() ({view}, error) {{",
            definition.name
        ));
        writer.line(buffer);
        find_field(writer, offset, &format!("{view}{{}}"));
        match field.field_type {
            FieldType::Vector(_) => {
                writer.line("vector, err := buffer.GetVector(position)");
                return_on_error(writer, &format!("{view}{{}}"));
                writer.line(format!("return {view}{{vector: vector}}, nil"));
            }
            FieldType::StructArray(index) => {
                let size = self.schema.definition(index).struct_layout().size;
                writer.line(format!(
                    "bytes, err := buffer.GetStructArray(position, {size})"
                ));
                return_on_error(writer, &format!("{view}{{}}"));
                writer.line(format!("return {view}{{bytes: bytes}}, nil"));
            }
            _ => unreachable!("only vectors and arrays of structs have views"),
        }
        writer.close("}");
    }

    fn structure(&self, writer: &mut CodeWriter, definition: &Definition) {
        let name = &definition.name;
        let size = definition.struct_layout().size;

        writer.blank();
        writer.lines(&go_doc(&definition.docs));
        writer.open(format!("type {name} struct {{"));
        let fields: Vec<(&[String], String, String)> = definition
            .fields
            .iter()
            .map(|field| {
                (
                    field.docs.as_slice(),
                    exported(&field.name),
                    self.input_type(field.field_type),
                )
            })
            .collect();
        struct_fields(writer, &fields);
        writer.close("}");

        writer.blank();
        writer.lines(&prose(&[
            format!(
                "MarshalBinary returns the {size} bytes of {}: its scalars,",
                article(name)
            ),
            "little-endian, one after another. It never fails.".to_owned(),
        ]));
        writer.open(format!(
            "func ({STRUCT} {name}) MarshalBinary() ([]byte, error) {{"
        ));
        writer.line(format!(
            "return {STRUCT}.AppendBinary(make([]byte, 0, {size}))"
        ));
        writer.close("}");

        writer.blank();
        writer.lines(&prose(&[
            format!(
                "AppendBinary appends the {size} bytes of {} to bytes, as",
                article(name)
            ),
            format!("[{name}.MarshalBinary] writes them, and returns the extended bytes. It"),
            "never fails.".to_owned(),
        ]));
        writer.open(format!(
            "func ({STRUCT} {name}) AppendBinary(bytes []byte) ([]byte, error) {{"
        ));
        writer.line("start := len(bytes)");
        writer.line(format!("bytes = append(bytes, make([]byte, {size})...)"));
        writer.line(format!("{STRUCT}.put(bytes[start:])"));
        writer.line("return bytes, nil");
        writer.close("}");

        writer.blank();
        writer.lines(&prose(&[
            format!(
                "UnmarshalBinary reads {} from the start of bytes. It fails",
                article(name)
            ),
            format!("with a {DECODE_ERROR} if bytes are shorter than {size}."),
        ]));
        writer.open(format!(
            "func ({STRUCT} *{name}) UnmarshalBinary(bytes []byte) error {{"
        ));
        writer.open(format!("if len(bytes) < {size} {{"));
        writer.line(format!(
            "return &tafla.DecodeError{{Kind: tafla.OutOfRange, ByteLength: {size}, Available: len(bytes)}}"
        ));
        writer.close("}");
        writer.blank();
        writer.line(format!("{STRUCT}.read(bytes)"));
        writer.line("return nil");
        writer.close("}");

        self.struct_access(writer, definition, true);
        self.struct_access(writer, definition, false);
    }

    /// A struct's `read()`, which reads its scalars from bytes, or its
    /// `put()`, which writes them into bytes, each at its offset, and a
    /// struct within it with its own method
    fn struct_access(&self, writer: &mut CodeWriter, definition: &Definition, read: bool) {
        let name = &definition.name;
        let size = definition.struct_layout().size;

        writer.blank();
        if read {
            writer.lines(&prose(&[
                format!(
                    "read reads the scalars of {} from the start of bytes,",
                    article(name)
                ),
                format!("which hold at least its {size} bytes"),
            ]));
            writer.open(format!("func ({STRUCT} *{name}) read(bytes []byte) {{"));
        } else {
            writer.lines(&prose(&[
                format!(
                    "put writes the scalars of {} into the start of bytes,",
                    article(name)
                ),
                format!("which hold at least its {size} bytes"),
            ]));
            writer.open(format!("func ({STRUCT} *{name}) put(bytes []byte) {{"));
        }
        // The last byte bounds every access, so that the compiler checks it
        // alone
        writer.line(format!("_ = bytes[{}]", size - 1));

        let mut offset = 0;
        for field in &definition.fields {
            let member = format!("{STRUCT}.{}", exported(&field.name));
            let at = if offset == 0 {
                "bytes".to_owned()
            } else {
                format!("bytes[{offset}:]")
            };

            match field.field_type {
                FieldType::Scalar(scalar) => {
                    if read {
                        writer.line(format!("{member} = {}", read_scalar(scalar, offset)));
                    } else {
                        put_scalar(writer, scalar, &member, "bytes", offset);
                    }
                    offset += usize::from(scalar.size());
                }
                FieldType::Struct(index) => {
                    let method = if read { "read" } else { "put" };
                    writer.line(format!("{member}.{method}({at})"));
                    offset += self.schema.definition(index).struct_layout().size;
                }
                _ => unreachable!("structs hold scalars and structs only"),
            }
        }
        writer.close("}");
    }

    /// The struct of the values that write a message or table, with the
    /// methods that write it: a message's binary marshaling, and a nested
    /// table's methods with which its parent sizes and writes it
    fn fields_struct(&self, writer: &mut CodeWriter, index: usize) {
        let definition = self.schema.definition(index);
        let name = &definition.name;

        writer.blank();
        writer.lines(&prose(&[format!(
            "{name}Fields are the fields of {}, to write.",
            article(name)
        )]));
        writer.open(format!("type {name}Fields struct {{"));
        let fields: Vec<(&[String], String, String)> = definition
            .fields
            .iter()
            .map(|field| {
                (
                    field.docs.as_slice(),
                    exported(&field.name),
                    self.input_type(field.field_type),
                )
            })
            .collect();
        struct_fields(writer, &fields);
        writer.close("}");

        match definition.kind {
            Kind::Message(layout) => self.marshal(writer, definition, layout),
            Kind::Table => match self.fixed_tables[index] {
                Some(size) => self.put_table(writer, definition, size),
                None => self.size_and_write(writer, definition),
            },
            Kind::Struct(_) => unreachable!("structs are written by their own methods"),
        }
    }

    /// A message's binary marshaling, which sizes its fields and then writes
    /// them into bytes of that length
    fn marshal(&self, writer: &mut CodeWriter, definition: &Definition, layout: Layout) {
        let name = &definition.name;
        let fields = definition.fields.len();

        writer.blank();
        writer.lines(&prose(&[
            format!(
                "MarshalBinary writes {} with every field. It fails with a",
                article(name)
            ),
            format!(
                "[*tafla.BuildError] if it's longer than its offset type, {}, addresses.",
                layout.offset_type.name()
            ),
        ]));
        writer.open(format!(
            "func ({FIELDS} {name}Fields) MarshalBinary() ([]byte, error) {{"
        ));
        writer.line(format!("return {FIELDS}.AppendBinary(nil)"));
        writer.close("}");

        writer.blank();
        writer.lines(&prose(&[
            format!(
                "AppendBinary appends {} with every field to bytes, as",
                article(name)
            ),
            format!("[{name}Fields.MarshalBinary] writes it, and returns the extended bytes,"),
            "into their capacity when they have room. It fails as MarshalBinary does.".to_owned(),
        ]));
        writer.open(format!(
            "func ({FIELDS} {name}Fields) AppendBinary(bytes []byte) ([]byte, error) {{"
        ));
        let plan = self.plan(definition);
        if plan.whole {
            self.append_whole(writer, definition, layout, &plan);
            writer.close("}");
            return;
        }

        if layout.version.is_some() {
            writer.line(format!(
                "sizer, err := tafla.NewVersionedTableSizer({fields}, {name}{{}}.layout(), {name}FormatVersion)"
            ));
        } else {
            writer.line(format!(
                "sizer, err := tafla.NewTableSizer({fields}, {name}{{}}.layout())"
            ));
        }
        return_on_error(writer, "nil");
        self.sizes(writer, definition, "&sizer");
        writer.blank();
        writer.line("writer, err := sizer.AppendWriter(bytes)");
        return_on_error(writer, "nil");
        self.writes(writer, definition, "&writer");
        writer.blank();
        writer.line("return writer.Bytes()");
        writer.close("}");
    }

    /// The body of `AppendBinary()` of a message whose fields are all of fixed
    /// size but a string after them, which it lays out in the bytes that the
    /// runtime appends and writes the header of
    fn append_whole(
        &self,
        writer: &mut CodeWriter,
        definition: &Definition,
        layout: Layout,
        plan: &Plan,
    ) {
        let name = &definition.name;
        let fields = definition.fields.len();
        let string = definition.fields.get(plan.fixed);

        // Only the string's length isn't fixed
        let end = plan.end(fields);
        let length = match string {
            Some(field) => format!(
                "{}+uint64(len({FIELDS}.{}))",
                end + plan.width,
                exported(&field.name)
            ),
            None => end.to_string(),
        };
        let table = if fields == 0 { "_" } else { "table" };
        if layout.version.is_some() {
            writer.line(format!(
                "bytes, {table}, err := tafla.AppendVersionedTable(bytes, {fields}, {name}{{}}.layout(), {name}FormatVersion, {length})"
            ));
        } else {
            writer.line(format!(
                "bytes, {table}, err := tafla.AppendTable(bytes, {fields}, {name}{{}}.layout(), {length})"
            ));
        }
        return_on_error(writer, "nil");

        if fields > 0 {
            writer.blank();
            self.put_fixed(writer, "table", definition, plan, string);
        }
        writer.blank();
        writer.line("return bytes, nil");
    }

    /// A table's `put()`, which writes a nested table of only fields of fixed
    /// size, of `size` bytes, whole: its offsets and its fields
    fn put_table(&self, writer: &mut CodeWriter, definition: &Definition, size: usize) {
        let name = &definition.name;
        let fields = definition.fields.len();

        writer.blank();
        writer.lines(&prose(&[
            format!(
                "put writes {} whole, its offsets and its fields, into the start",
                article(name)
            ),
            format!("of bytes, which hold at least its {size} bytes, where its parent's"),
            "writer reserved them".to_owned(),
        ]));
        writer.open(format!(
            "func ({FIELDS} *{name}Fields) put(bytes []byte) {{"
        ));
        let plan = Plan {
            header: 0,
            width: NESTED_OFFSET_SIZE,
            fixed: fields,
            bytes: size - fields * NESTED_OFFSET_SIZE,
            whole: true,
        };
        if fields > 0 {
            self.put_fixed(writer, "bytes", definition, &plan, None);
        }
        writer.close("}");
    }

    /// The lines that write the offsets and values of the fields that `plan`
    /// lays out into `bytes`, which hold the table from its start, and then
    /// those of `string`, the string after them, when it's given
    fn put_fixed(
        &self,
        writer: &mut CodeWriter,
        bytes: &str,
        definition: &Definition,
        plan: &Plan,
        string: Option<&Field>,
    ) {
        let fields = &definition.fields[..plan.fixed];
        let end = plan.end(definition.fields.len());

        // The last byte before the string's bounds every access, so that the
        // compiler checks it alone
        let last = if string.is_some() {
            end + plan.width
        } else {
            end
        };
        writer.line(format!("_ = {bytes}[{}]", last - 1));

        // The fields follow the header and the offsets
        let mut position = plan.header + definition.fields.len() * plan.width;
        let mut positions = Vec::with_capacity(fields.len());
        for field in fields {
            positions.push(position);
            position += self.fixed_size(field.field_type).unwrap_or_default();
        }
        for (index, &position) in positions.iter().enumerate() {
            put_slot(
                writer,
                bytes,
                plan.width,
                plan.header + index * plan.width,
                &position.to_string(),
            );
        }
        if string.is_some() {
            put_slot(
                writer,
                bytes,
                plan.width,
                plan.header + fields.len() * plan.width,
                &end.to_string(),
            );
        }

        for (field, &position) in fields.iter().zip(&positions) {
            let member = format!("{FIELDS}.{}", exported(&field.name));
            match field.field_type {
                FieldType::Scalar(scalar) => put_scalar(writer, scalar, &member, bytes, position),
                FieldType::Struct(_) | FieldType::Table(_) => {
                    writer.line(format!("{member}.put({})", at(bytes, position)));
                }
                _ => unreachable!("only fields of fixed size are laid out"),
            }
        }

        if let Some(field) = string {
            let member = format!("{FIELDS}.{}", exported(&field.name));
            let count = format!("uint{}(len({member}))", 8 * plan.width);
            put_slot(writer, bytes, plan.width, end, &count);
            writer.line(format!("copy({bytes}[{}:], {member})", end + plan.width));
        }
    }

    /// The methods with which a nested table's parent sizes and writes it
    fn size_and_write(&self, writer: &mut CodeWriter, definition: &Definition) {
        let name = &definition.name;
        let fields = definition.fields.len();

        writer.blank();
        writer.lines(&prose(&[
            format!(
                "size adds {} to its parent's sizer, after the field or vector",
                article(name)
            ),
            "that holds it".to_owned(),
        ]));
        writer.open(format!(
            "func ({FIELDS} *{name}Fields) size(sizer *tafla.TableSizer) {{"
        ));
        writer.line(format!("parent := sizer.StartTable({fields})"));
        self.sizes(writer, definition, "sizer");
        writer.line("sizer.EndTable(parent)");
        writer.close("}");

        writer.blank();
        writer.lines(&prose(&[
            format!(
                "write writes {} where its parent's writer is, after the field",
                article(name)
            ),
            "or vector that holds it".to_owned(),
        ]));
        writer.open(format!(
            "func ({FIELDS} *{name}Fields) write(writer *tafla.TableWriter) {{"
        ));
        writer.line(format!("parent := writer.StartTable({fields})"));
        self.writes(writer, definition, "writer");
        writer.line("writer.EndTable(parent)");
        writer.close("}");
    }

    /// The calls that add a table's fields to its sizer, in order, with
    /// `sizer`, the expression of the sizer that nested tables take
    fn sizes(&self, writer: &mut CodeWriter, definition: &Definition, sizer: &str) {
        let plan = self.plan(definition);
        if plan.fixed > 0 {
            writer.line(format!("sizer.AddFields({}, {})", plan.fixed, plan.bytes));
        }

        for field in &definition.fields[plan.fixed..] {
            let value = format!("{FIELDS}.{}", exported(&field.name));
            match field.field_type {
                FieldType::Scalar(scalar) => {
                    writer.line(format!("sizer.Add{}()", method(scalar.stored())));
                }
                FieldType::Array(scalar) => {
                    writer.line(format!("sizer.Add{}Array(len({value}))", method(scalar)));
                }
                FieldType::String => writer.line(format!("sizer.AddString({value})")),
                FieldType::Struct(index) => {
                    let size = self.schema.definition(index).struct_layout().size;
                    writer.line(format!("sizer.AddStruct({size})"));
                }
                FieldType::StructArray(index) => {
                    let layout = self.schema.definition(index).struct_layout();
                    writer.line(format!(
                        "sizer.AddStructArray(len({value}), {}, {})",
                        layout.size,
                        alignment_constant(layout.alignment)
                    ));
                }
                FieldType::Table(index) => {
                    let alignment = self.schema.table_alignment(index);
                    writer.line(format!("sizer.AddTable({})", alignment_constant(alignment)));
                    match self.fixed_tables[index] {
                        Some(size) => writer.line(format!("sizer.AddTableBytes(1, {size})")),
                        None => writer.line(format!("{value}.size({sizer})")),
                    }
                }
                FieldType::Vector(index) => {
                    writer.line(format!("sizer.AddVector(len({value}))"));
                    if let Some(size) = self.fixed_tables[index] {
                        writer.line(format!("sizer.AddTableBytes(len({value}), {size})"));
                    } else {
                        writer.open(format!("for index := range {value} {{"));
                        writer.line(format!("{value}[index].size({sizer})"));
                        writer.close("}");
                    }
                }
            }
        }
    }

    /// The calls that write a table's fields, each with its index, in the
    /// order that `sizes()` added them, with `table_writer`, the expression of
    /// the writer that nested tables take
    fn writes(&self, writer: &mut CodeWriter, definition: &Definition, table_writer: &str) {
        // The locals that a field needs, declared by the first that does
        let mut declared_boolean = false;
        let mut declared_structs = false;
        let mut declared_vector = false;

        let plan = self.plan(definition);
        if plan.fixed > 0 {
            writer.line(format!("fixed := writer.ReserveFields({})", plan.bytes));
            self.put_fixed(writer, "fixed", definition, &plan, None);
        }

        for (index, field) in definition.fields.iter().enumerate().skip(plan.fixed) {
            let value = format!("{FIELDS}.{}", exported(&field.name));
            match field.field_type {
                FieldType::Scalar(Scalar::Bool) => {
                    if declared_boolean {
                        writer.line("boolean = 0");
                    } else {
                        writer.line("var boolean uint8");
                        declared_boolean = true;
                    }
                    writer.open(format!("if {value} {{"));
                    writer.line("boolean = 1");
                    writer.close("}");
                    writer.line(format!("writer.SetUint8({index}, boolean)"));
                }
                FieldType::Scalar(scalar) => {
                    writer.line(format!("writer.Set{}({index}, {value})", method(scalar)));
                }
                FieldType::Array(scalar) => {
                    writer.line(format!(
                        "writer.Set{}Array({index}, {value})",
                        method(scalar)
                    ));
                }
                FieldType::String => writer.line(format!("writer.SetString({index}, {value})")),
                FieldType::Struct(struct_index) => {
                    let size = self.schema.definition(struct_index).struct_layout().size;
                    writer.line(format!(
                        "{value}.put(writer.ReserveStruct({index}, {size}))"
                    ));
                }
                // The structs are written into the bytes that the writer
                // reserves for them, without collecting them first
                FieldType::StructArray(struct_index) => {
                    let layout = self.schema.definition(struct_index).struct_layout();
                    let assign = if declared_structs { "=" } else { ":=" };
                    declared_structs = true;
                    writer.line(format!(
                        "structs {assign} writer.ReserveStructArray({index}, len({value}), {}, {})",
                        layout.size,
                        alignment_constant(layout.alignment)
                    ));
                    writer.open(format!("for item := range {value} {{"));
                    writer.line(format!("{value}[item].put(structs[item*{}:])", layout.size));
                    writer.close("}");
                }
                FieldType::Table(table_index) => {
                    let alignment = self.schema.table_alignment(table_index);
                    writer.line(format!(
                        "writer.SetTable({index}, {})",
                        alignment_constant(alignment)
                    ));
                    match self.fixed_tables[table_index] {
                        Some(size) => {
                            writer.line(format!("{value}.put(writer.ReserveTableBytes({size}))"));
                        }
                        None => writer.line(format!("{value}.write({table_writer})")),
                    }
                }
                FieldType::Vector(item_index) => {
                    let assign = if declared_vector { "=" } else { ":=" };
                    declared_vector = true;
                    writer.line(format!(
                        "vector {assign} writer.SetVector({index}, len({value}))"
                    ));
                    writer.open(format!("for item := range {value} {{"));
                    match self.fixed_tables[item_index] {
                        Some(size) => writer.line(format!(
                            "{value}[item].put(writer.ReserveTableBytes({size}))"
                        )),
                        None => writer.line(format!("{value}[item].write({table_writer})")),
                    }
                    writer.line("writer.SetItemEnd(vector, item)");
                    writer.close("}");
                }
            }
        }
    }

    fn value_type(&self, field_type: FieldType) -> String {
        match field_type {
            FieldType::Scalar(scalar) => scalar_type(scalar).to_owned(),
            FieldType::Array(Scalar::Uint8) => "[]byte".to_owned(),
            FieldType::Array(scalar) => format!("tafla.ArrayView[{}]", scalar_type(scalar)),
            FieldType::String => "string".to_owned(),
            FieldType::Struct(index) | FieldType::Table(index) => {
                self.schema.definition(index).name.clone()
            }
            FieldType::StructArray(index) | FieldType::Vector(index) => {
                format!("[]{}", self.schema.definition(index).name)
            }
        }
    }

    fn input_type(&self, field_type: FieldType) -> String {
        match field_type {
            FieldType::Scalar(scalar) => scalar_type(scalar).to_owned(),
            FieldType::Array(Scalar::Uint8) => "[]byte".to_owned(),
            FieldType::Array(scalar) => format!("[]{}", scalar_type(scalar)),
            FieldType::String => "string".to_owned(),
            FieldType::Struct(index) => self.schema.definition(index).name.clone(),
            FieldType::StructArray(index) => format!("[]{}", self.schema.definition(index).name),
            FieldType::Table(index) => format!("{}Fields", self.schema.definition(index).name),
            FieldType::Vector(index) => format!("[]{}Fields", self.schema.definition(index).name),
        }
    }
}

/// The lines that find a field's position from `offset`, a call that returns
/// it and an error, returning `zero` and the error if it fails
fn find_field(writer: &mut CodeWriter, offset: &str, zero: &str) {
    writer.line(format!("position, err := {offset}"));
    return_on_error(writer, zero);
}

fn return_on_error(writer: &mut CodeWriter, zero: &str) {
    writer.open("if err != nil {");
    writer.line(format!("return {zero}, err"));
    writer.close("}");
}

/// The documentation of a getter: the field's own, and when it fails
fn getter_docs(getter: &str, docs: &[String], condition: &str) -> Vec<String> {
    let mut lines = docs.to_vec();
    if lines.is_empty() {
        lines.extend(wrap(&format!(
            "{getter} fails with a {DECODE_ERROR} {condition}"
        )));
    } else {
        lines.push(String::new());
        lines.extend(wrap(&format!("It fails with a {DECODE_ERROR} {condition}")));
    }
    lines
}

/// The width of the text of a top-level comment, after `// `, which the
/// generated prose wraps at, as Go's code is commonly wrapped at 80 columns
const COMMENT_WIDTH: usize = 77;

/// The lines of a doc comment of the generated code's own prose, given in
/// parts that it joins with spaces and wraps at [`COMMENT_WIDTH`], which gofmt
/// keeps, since it doesn't reflow comments
fn prose(parts: &[String]) -> Vec<String> {
    go_doc(&wrap(&parts.join(" ")))
}

/// Text wrapped at [`COMMENT_WIDTH`], between its words
fn wrap(text: &str) -> Vec<String> {
    let mut lines = Vec::new();
    let mut line = String::new();
    for word in text.split_whitespace() {
        if !line.is_empty() && line.chars().count() + 1 + word.chars().count() > COMMENT_WIDTH {
            lines.push(std::mem::take(&mut line));
        }
        if !line.is_empty() {
            line.push(' ');
        }
        line.push_str(word);
    }
    if !line.is_empty() {
        lines.push(line);
    }
    lines
}

/// The fields of a struct, each after its documentation, which isn't
/// reformatted, and aligned as gofmt aligns them: the types of consecutive
/// fields start in one column, and a comment between two fields starts
/// another run of them
fn struct_fields(writer: &mut CodeWriter, fields: &[(&[String], String, String)]) {
    let mut start = 0;
    while start < fields.len() {
        let mut end = start + 1;
        while end < fields.len() && fields[end].0.is_empty() {
            end += 1;
        }
        let width = fields[start..end]
            .iter()
            .map(|(_, name, _)| name.len())
            .max()
            .unwrap_or(0);

        for (docs, name, field_type) in &fields[start..end] {
            for line in *docs {
                writer.line(format!("// {line}").trim_end());
            }
            writer.line(format!("{name:width$} {field_type}"));
        }
        start = end;
    }
}

/// The view of a vector of a table, which reads each item when it's asked
/// for, from the item's end and the end of the item before it
fn vector_view(writer: &mut CodeWriter, definition: &Definition) {
    let table = &definition.name;
    let view = format!("{table}Vector");

    writer.blank();
    writer.lines(&prose(&[format!(
        "{view} is a vector of [{table}]s, which reads each item when it's asked for."
    )]));
    writer.open(format!("type {view} struct {{"));
    writer.line("vector tafla.Vector");
    writer.close("}");

    writer.blank();
    writer.lines(&prose(&["Len returns the number of items.".to_owned()]));
    writer.open(format!("func ({VIEW} {view}) Len() int {{"));
    writer.line(format!("return {VIEW}.vector.Len()"));
    writer.close("}");

    writer.blank();
    writer.lines(&prose(&[
        "Get reads item index, without reading the others. It fails with a".to_owned(),
        format!("{DECODE_ERROR} if the item lies outside the bytes, and panics if"),
        "index is out of range, as indexing a slice does.".to_owned(),
    ]));
    writer.open(format!(
        "func ({VIEW} {view}) Get(index int) ({table}, error) {{"
    ));
    writer.line(format!("bytes, err := {VIEW}.vector.GetInPlace(index)"));
    writer.line(format!("return {table}{{bytes: bytes}}, err"));
    writer.close("}");

    writer.blank();
    writer.lines(&prose(&[
        "All returns an iterator over the items, which reads each item's end".to_owned(),
        "once. An item that fails doesn't keep the others from being read.".to_owned(),
    ]));
    writer.open(format!(
        "func ({VIEW} {view}) All() iter.Seq2[{table}, error] {{"
    ));
    writer.open(format!("return func(yield func({table}, error) bool) {{"));
    writer.open(format!(
        "for bytes, err := range {VIEW}.vector.ItemsInPlace() {{"
    ));
    writer.open(format!("if !yield({table}{{bytes: bytes}}, err) {{"));
    writer.line("return");
    writer.close("}");
    writer.close("}");
    writer.close("}");
    writer.close("}");
}

/// The view of an array of a struct, which reads each struct when it's
/// asked for, from their bytes
fn struct_array_view(writer: &mut CodeWriter, definition: &Definition) {
    let structure = &definition.name;
    let view = format!("{structure}Array");
    let size = definition.struct_layout().size;

    writer.blank();
    writer.lines(&prose(&[format!(
        "{view} is an array of [{structure}]s, which reads each struct when it's asked for."
    )]));
    writer.open(format!("type {view} struct {{"));
    writer.line("bytes []byte");
    writer.close("}");

    writer.blank();
    writer.lines(&prose(&["Len returns the number of structs.".to_owned()]));
    writer.open(format!("func ({VIEW} {view}) Len() int {{"));
    writer.line(format!("return len({VIEW}.bytes) / {size}"));
    writer.close("}");

    writer.blank();
    writer.lines(&prose(&[
        "Get reads struct index. It panics if index is out of range, as".to_owned(),
        "indexing a slice does.".to_owned(),
    ]));
    writer.open(format!(
        "func ({VIEW} {view}) Get(index int) {structure} {{"
    ));
    writer.line(format!("var item {structure}"));
    writer.line(format!("item.read({VIEW}.bytes[index*{size}:])"));
    writer.line("return item");
    writer.close("}");

    writer.blank();
    writer.lines(&prose(&[
        "All returns an iterator over the indices and structs.".to_owned(),
    ]));
    writer.open(format!(
        "func ({VIEW} {view}) All() iter.Seq2[int, {structure}] {{"
    ));
    writer.open(format!("return func(yield func(int, {structure}) bool) {{"));
    writer.open(format!("for index := range {VIEW}.Len() {{"));
    writer.open(format!("if !yield(index, {VIEW}.Get(index)) {{"));
    writer.line("return");
    writer.close("}");
    writer.close("}");
    writer.close("}");
    writer.close("}");
}

/// The expression that reads a scalar at `offset` in `bytes`
fn read_scalar(scalar: Scalar, offset: usize) -> String {
    let at = if offset == 0 {
        "bytes".to_owned()
    } else {
        format!("bytes[{offset}:]")
    };
    let bits = |size: u8| format!("binary.LittleEndian.Uint{}({at})", 8 * size);

    match scalar {
        Scalar::Bool => format!("bytes[{offset}] != 0"),
        Scalar::Int8 => format!("int8(bytes[{offset}])"),
        Scalar::Uint8 => format!("bytes[{offset}]"),
        Scalar::Int16 | Scalar::Int32 | Scalar::Int64 => {
            format!("{}({})", scalar_type(scalar), bits(scalar.size()))
        }
        Scalar::Uint16 | Scalar::Uint32 | Scalar::Uint64 => bits(scalar.size()),
        Scalar::Float32 => format!("math.Float32frombits({})", bits(4)),
        Scalar::Float64 => format!("math.Float64frombits({})", bits(8)),
    }
}

/// The lines that write the scalar `member` at `offset` in the slice `bytes`
fn put_scalar(writer: &mut CodeWriter, scalar: Scalar, member: &str, bytes: &str, offset: usize) {
    let at = at(bytes, offset);
    let put =
        |size: u8, value: String| format!("binary.LittleEndian.PutUint{}({at}, {value})", 8 * size);

    match scalar {
        Scalar::Bool => {
            writer.line(format!("{bytes}[{offset}] = 0"));
            writer.open(format!("if {member} {{"));
            writer.line(format!("{bytes}[{offset}] = 1"));
            writer.close("}");
        }
        Scalar::Int8 => writer.line(format!("{bytes}[{offset}] = byte({member})")),
        Scalar::Uint8 => writer.line(format!("{bytes}[{offset}] = {member}")),
        Scalar::Int16 | Scalar::Int32 | Scalar::Int64 => {
            let size = scalar.size();
            writer.line(put(size, format!("uint{}({member})", 8 * size)));
        }
        Scalar::Uint16 | Scalar::Uint32 | Scalar::Uint64 => {
            writer.line(put(scalar.size(), member.to_owned()));
        }
        Scalar::Float32 => writer.line(put(4, format!("math.Float32bits({member})"))),
        Scalar::Float64 => writer.line(put(8, format!("math.Float64bits({member})"))),
    }
}

/// The lines that write an offset, a count or a length, `value`, in `width`
/// bytes at `position` in the slice `bytes`
fn put_slot(writer: &mut CodeWriter, bytes: &str, width: usize, position: usize, value: &str) {
    match width {
        1 => writer.line(format!("{bytes}[{position}] = {value}")),
        2 => writer.line(format!(
            "binary.LittleEndian.PutUint16({}, {value})",
            at(bytes, position)
        )),
        _ => writer.line(format!(
            "binary.LittleEndian.PutUint32({}, {value})",
            at(bytes, position)
        )),
    }
}

/// The slice `bytes` from `offset`
fn at(bytes: &str, offset: usize) -> String {
    if offset == 0 {
        bytes.to_owned()
    } else {
        format!("{bytes}[{offset}:]")
    }
}

/// The width of an offset type's header slots, offsets and counts
const fn offset_size(offset_type: OffsetType) -> usize {
    match offset_type {
        OffsetType::Uint8 => 1,
        OffsetType::Uint16 => 2,
        OffsetType::Uint32 => 4,
    }
}

/// Finds the byte length of the table at `index` when its fields' sizes are
/// all fixed, and its nested tables' first, into `sizes` by its index, which
/// is `None` for any other definition, or one too long to lay out, and marks
/// it `visited`. Tables nest in place at most 64 deep, and each is sized once.
fn fixed_table_size(
    schema: &Schema,
    index: usize,
    sizes: &mut [Option<usize>],
    visited: &mut [bool],
) -> Option<usize> {
    if visited[index] {
        return sizes[index];
    }

    let definition = schema.definition(index);
    let mut size = Some(definition.fields.len().saturating_mul(NESTED_OFFSET_SIZE));
    if definition.kind != Kind::Table {
        size = None;
    }
    for field in &definition.fields {
        let Some(table) = size else {
            break;
        };
        let field_size = fixed_field_size(schema, field.field_type, |nested| {
            fixed_table_size(schema, nested, sizes, visited)
        });
        size = field_size.map(|field_size| table.saturating_add(field_size));
    }

    let size = size.filter(|&size| size <= MAX_LAID_OUT);
    sizes[index] = size;
    visited[index] = true;
    size
}

/// The byte length of a field whose size the schema fixes: a scalar's, a
/// struct's, or the length of a nested table that `table` gives, when its
/// fields' sizes are all fixed
fn fixed_field_size(
    schema: &Schema,
    field_type: FieldType,
    table: impl FnOnce(usize) -> Option<usize>,
) -> Option<usize> {
    match field_type {
        FieldType::Scalar(scalar) => Some(usize::from(scalar.size())),
        FieldType::Struct(index) => Some(schema.definition(index).struct_layout().size),
        FieldType::Table(index) => table(index),
        FieldType::Array(_)
        | FieldType::String
        | FieldType::StructArray(_)
        | FieldType::Vector(_) => None,
    }
}

/// The layout of a message, as an expression of the runtime's
fn layout_expression(layout: Layout) -> String {
    let mut expression = "tafla.TableLayout{}".to_owned();
    if layout.sized {
        expression.push_str(".Sized()");
    }
    if layout.version.is_some() {
        expression.push_str(".Versioned()");
    }
    match layout.offset_type {
        OffsetType::Uint8 => expression.push_str(".WithOffsetType(tafla.Uint8)"),
        OffsetType::Uint16 => expression.push_str(".WithOffsetType(tafla.Uint16)"),
        OffsetType::Uint32 => {}
    }
    expression
}

/// The zero value of a getter's type, which it returns with an error
fn zero_value(value_type: &str) -> String {
    match value_type {
        "bool" => "false".to_owned(),
        "string" => "\"\"".to_owned(),
        _ if value_type.starts_with("[]") => "nil".to_owned(),
        _ if Scalar::from_name(value_type).is_some() => "0".to_owned(),
        _ => format!("{value_type}{{}}"),
    }
}

