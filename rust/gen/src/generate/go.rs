/// A field's exported name, in `PascalCase`, with a `_` after it if it would
/// clash with a method that the generated types declare
fn exported(name: &str) -> String {
    let exported = pascal_case(name);
    if MEMBERS.contains(&name) {
        format!("{exported}_")
    } else {
        exported
    }
}

/// A `snake_case` name in `PascalCase`, as Go exports it. Like `camelCase`,
/// it drops the underscores, which the checker keeps names distinct without.
fn pascal_case(snake: &str) -> String {
    snake
        .split('_')
        .map(|word| {
            let mut characters = word.chars();
            characters
                .next()
                .map(|first| first.to_ascii_uppercase().to_string() + characters.as_str())
                .unwrap_or_default()
        })
        .collect()
}

